"""Зона проверки: сечение вокруг оси пути, в котором объект мешает поезду.

Зона -- ступени (низ, верх над головкой рельса, полуширина от оси пути), м.
По умолчанию -- прямоугольник RECT_DEFAULT (+-1м, 0.15-2м над рельсом).

GAUGE_METRO -- ПРИБЛИЖЕНИЕ габарита вагона метро (ширина кузова ~2.7м, высота
~3.7м), не выверено по ГОСТ 23961. Низ уже кузова: там тележки, а сбоку от
пути -- контактный рельс. По умолчанию не используется: на чистых записях он
поднимает тревоги в 86% кадров против 27% у прямоугольника (свод над поездом на
3-3.7м и стены у бортов на 1.2-1.35м от оси).
"""
import numpy as np

GAUGE_METRO = (
    (0.15, 0.35, 1.20),
    (0.35, 3.70, 1.35),
)


def rect_zone(clearance=0.15, height=2.0, half_width=1.0):
    return ((clearance, height, half_width),)


RECT_DEFAULT = rect_zone()


def zone_mask(lat, z_rel, zone):
    """Точки внутри зоны: lat -- смещение от оси, z_rel -- высота над головкой рельса."""
    m = np.zeros(len(z_rel), bool)
    for lo, hi, hw in zone:
        m |= (z_rel > lo) & (z_rel < hi) & (np.abs(lat) < hw)
    return m
